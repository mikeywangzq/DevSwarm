def package_project(project_dir: Path, output_dir: Optional[Path] = None) -> Path:
    """
    打包项目为zip文件

    Args:
        project_dir: 项目目录
        output_dir: 输出目录（可选）

    Returns:
        zip文件路径
    """
    if output_dir is None:
        output_dir = project_dir.parent

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    zip_filename = f"{project_dir.name}.zip"
    zip_path = output_dir / zip_filename

    logger.info(f"Packaging project to {zip_path}")

    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
        for root, dirs, files in os.walk(project_dir):
            # 排除某些目录
            dirs[:] = [d for d in dirs if d not in ['__pycache__', 'venv', '.git']]

            for file in files:
                file_path = Path(root) / file
                arcname = file_path.relative_to(project_dir.parent)
                zipf.write(file_path, arcname)

    logger.info(f"Project packaged successfully: {zip_path}")
    return zip_path


def finalize_project(project_id: str, workspace_root: str, requirement: str) -> Dict[str, Any]:
    """
    完成项目打包

    Args:
        project_id: 项目ID
        workspace_root: 工作区根目录
        requirement: 用户需求

    Returns:
        打包结果
    """
    project_dir = Path(workspace_root) / project_id
    backend_dir = project_dir / "backend"
    frontend_dir = project_dir / "frontend"

    # 创建Docker文件
    create_docker_compose(project_dir)
    create_backend_dockerfile(backend_dir)
    create_frontend_dockerfile(frontend_dir)

    # 创建项目README
    create_project_readme(project_dir, requirement)

    # 打包项目
    zip_path = package_project(project_dir)

    return {
        "project_dir": str(project_dir),
        "zip_file": str(zip_path),
        "files": [
            "docker-compose.yml",
            "README.md",
            "backend/Dockerfile",
            "frontend/Dockerfile"
        ]
    }
