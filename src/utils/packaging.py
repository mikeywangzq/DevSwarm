"""
Packaging utilities
打包生成的项目
"""
import os
import shutil
import zipfile
from pathlib import Path
from typing import Optional
import logging

logger = logging.getLogger(__name__)


def create_docker_compose(project_dir: Path) -> Path:
    """
    创建docker-compose.yml文件

    Args:
        project_dir: 项目目录

    Returns:
        docker-compose.yml文件路径
    """
    docker_compose_content = """version: '3.8'

services:
  backend:
    build: ./backend
    ports:
      - "5000:5000"
    volumes:
      - ./backend:/app
    environment:
      - FLASK_APP=app.py
      - FLASK_ENV=development
    command: python app.py

  frontend:
    build: ./frontend
    ports:
      - "8000:8000"
    volumes:
      - ./frontend:/app
    depends_on:
      - backend
    command: python -m http.server 8000

volumes:
  backend_data:
"""

    compose_file = project_dir / "docker-compose.yml"
    with open(compose_file, 'w', encoding='utf-8') as f:
        f.write(docker_compose_content)

    logger.info(f"Created docker-compose.yml at {compose_file}")
    return compose_file


def create_backend_dockerfile(backend_dir: Path) -> Path:
    """创建后端Dockerfile"""
    dockerfile_content = """FROM python:3.9-slim

WORKDIR /app

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY . .

EXPOSE 5000

CMD ["python", "app.py"]
"""

    dockerfile = backend_dir / "Dockerfile"
    with open(dockerfile, 'w', encoding='utf-8') as f:
        f.write(dockerfile_content)

    logger.info(f"Created Dockerfile at {dockerfile}")
    return dockerfile


def create_frontend_dockerfile(frontend_dir: Path) -> Path:
    """创建前端Dockerfile"""
    dockerfile_content = """FROM python:3.9-slim

WORKDIR /app

COPY . .

EXPOSE 8000

CMD ["python", "-m", "http.server", "8000"]
"""

    dockerfile = frontend_dir / "Dockerfile"
    with open(dockerfile, 'w', encoding='utf-8') as f:
        f.write(dockerfile_content)

    logger.info(f"Created Dockerfile at {dockerfile}")
    return dockerfile


